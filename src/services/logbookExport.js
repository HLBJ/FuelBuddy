import { escapeCsvField } from './exportService.js'
import { saveFile } from './fileService.js'
import { taxYearRange } from './logbookService.js'
import { toIsoDate } from './dateUtils.js'

/**
 * SARS travel logbook exports (Pro). The layout follows what SARS asks for: the
 * vehicle, the opening and closing odometer readings for the tax year, total,
 * business and private kilometres, and each business trip's date, distance,
 * destination and reason.
 */

const km = (n) => (n === null || n === undefined ? '' : Math.round(n).toLocaleString('en-ZA').replace(/ /g, ' '))
const dateText = (iso) => {
  const [y, m, d] = iso.split('-')
  return `${d}/${m}/${y}`
}
// Standard PDF fonts only cover basic Latin; keep text to that.
const plain = (s) => String(s ?? '').replace(/[–—]/g, '-').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E -ÿ]/g, '')

const vehicleLine = (v) => [v.name, [v.make, v.model].filter(Boolean).join(' '), v.registration].filter(Boolean).join(' · ')

export function logbookFileName(vehicle, taxYear, ext) {
  const slug = (vehicle.registration || vehicle.name).replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase()
  return `fuelbuddy-logbook-${slug || 'vehicle'}-${taxYear}.${ext}`
}

function summaryRows(year) {
  const { readings, summary } = year
  return [
    ['Opening odometer (1 March)', readings.openingOdometer === null ? 'Not recorded' : `${km(readings.openingOdometer)} km`],
    ['Closing odometer (end of February)', readings.closingOdometer === null ? 'Not recorded' : `${km(readings.closingOdometer)} km`],
    ['Total distance', `${km(summary.totalKm)} km${summary.hasReadings ? '' : ' (logged trips only)'}`],
    ['Business distance', `${km(summary.businessKm)} km`],
    ['Private distance', `${km(summary.privateKm)} km`],
    ['Business use', summary.businessShare === null ? 'Not available' : `${summary.businessShare.toFixed(1)}%`],
  ]
}

const TRIP_HEADERS = ['Date', 'Odometer start', 'Odometer end', 'Km', 'Type', 'From', 'To', 'Reason']
const tripRow = (t) => [
  dateText(t.date), km(t.startOdometer), km(t.endOdometer), km(t.distance), t.purpose === 'business' ? 'Business' : 'Private',
  t.origin || '', t.destination || '', t.reason || '',
]

/** CSV: summary block, then one row per trip (oldest first). */
export function buildLogbookCsv(vehicle, year) {
  const { start, end } = taxYearRange(year.taxYear)
  const lines = [
    ['FuelBuddy travel logbook'],
    ['Vehicle', vehicleLine(vehicle)],
    ['Tax year', `${year.taxYear} (${dateText(start)} - ${dateText(end)})`],
    ...summaryRows(year),
    [],
    TRIP_HEADERS,
    ...[...year.trips].reverse().map(tripRow),
  ]
  return '﻿' + lines.map((row) => row.map(escapeCsvField).join(',')).join('\r\n') + '\r\n'
}

/** PDF as bytes. jsPDF is loaded only when someone exports. */
export async function buildLogbookPdf(vehicle, year, { generated = new Date() } = {}) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')])
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const { start, end } = taxYearRange(year.taxYear)
  const green = [13, 110, 79]

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.text(plain(`Travel logbook - tax year ${year.taxYear}`), 14, 18)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.text(plain(`${dateText(start)} to ${dateText(end)}`), 14, 25)
  doc.text(plain(`Vehicle: ${vehicleLine(vehicle)}`), 14, 31)

  autoTable(doc, {
    startY: 36,
    body: summaryRows(year).map(([k, v]) => [plain(k), plain(v)]),
    theme: 'grid',
    styles: { fontSize: 9, cellPadding: 1.8 },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 70 } },
    margin: { left: 14, right: 14 },
  })

  autoTable(doc, {
    startY: doc.lastAutoTable.finalY + 8,
    head: [TRIP_HEADERS],
    body: [...year.trips].reverse().map((t) => tripRow(t).map(plain)),
    theme: 'striped',
    headStyles: { fillColor: green },
    styles: { fontSize: 8, cellPadding: 1.5, overflow: 'linebreak' },
    columnStyles: { 0: { cellWidth: 19 }, 1: { cellWidth: 19, halign: 'right' }, 2: { cellWidth: 19, halign: 'right' }, 3: { cellWidth: 12, halign: 'right' }, 4: { cellWidth: 15 } },
    margin: { left: 14, right: 14, bottom: 18 },
    didDrawPage: () => {
      const page = doc.internal.getNumberOfPages()
      doc.setFontSize(7.5)
      doc.setTextColor(110)
      doc.text(
        plain(`Generated by FuelBuddy on ${dateText(toIsoDate(generated))}. Keep this logbook with your tax records - SARS may ask for it.   Page ${page}`),
        14,
        doc.internal.pageSize.getHeight() - 8,
      )
      doc.setTextColor(0)
    },
  })
  if (!year.trips.length) doc.text('No trips recorded in this tax year.', 14, doc.lastAutoTable.finalY + 8)

  return new Uint8Array(doc.output('arraybuffer'))
}

export async function exportLogbook(vehicle, year, format) {
  if (format === 'pdf') {
    const bytes = await buildLogbookPdf(vehicle, year)
    return saveFile(bytes, logbookFileName(vehicle, year.taxYear, 'pdf'), { mimeType: 'application/pdf', title: 'Travel logbook' })
  }
  return saveFile(buildLogbookCsv(vehicle, year), logbookFileName(vehicle, year.taxYear, 'csv'), {
    mimeType: 'text/csv;charset=utf-8',
    title: 'Travel logbook',
  })
}
